"""
conftest.py  -  shared fixture paths and skip markers for the Hindcast tests (backlog H-903)

Run from the repository root or from software/ (the one-liner is in software/hindcast/README.md):

    .venv/bin/python -m pytest software/hindcast/tests -q

Fixture policy (DESIGN.md section 9). Nothing here touches the network. Every data fixture is a local,
git-ignored file set; a test that needs one asks for the fixture and is SKIPPED, not failed, when it is
missing, so the suite passes on a fresh clone with only the committed files:

    results/example_2026-09-06/            five result CSVs + summary.* of the documented optimizer run
    variants/*.csv                          the no_change replay of 2026-09-06 06-09Z
    hindcast/tests/fixtures/study_example/  fixture study directory, generated by tests/make_fixtures.py (H-003)
    ns_cache/<host>/                        Nightscout day cache, 2026-08-30..2026-09-07 on the author's machine

Markers (register here, use as `@pytest.mark.<name>`):

    needs_cache            skip unless the whole cached window CACHE_DAYS exists in ns_cache/<host>/
    needs_cache("<day>")   skip unless that UTC day (entries + devicestatus) is cached
    needs_optuna           skip unless `import optuna` works
    needs_gh               skip unless the `gh` CLI is on PATH (tests still never create anything)
    slow                   deselected unless `--run-slow` is given (replays, multi-worker runs)

Path constants are plain module attributes so a test can also import them directly:
`from hindcast.tests.conftest import RESULTS_EXAMPLE_DIR`.
"""
