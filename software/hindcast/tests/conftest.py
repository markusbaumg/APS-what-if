def ns_host(settings_path=NS_SETTINGS):
    """Host part of nightscout.url in ns_settings.json, or None when the file or key is missing."""
    try:
        with open(settings_path, encoding='utf-8') as fh:
            url = json.load(fh)['nightscout']['url']
    except (OSError, KeyError, ValueError, TypeError):
        return None
    if not url:
        return None
    return url.split('://', 1)[-1].split('/', 1)[0]


def ns_cache_dir(settings_path=NS_SETTINGS):
    """software/ns_cache/<host> for the configured host (nightscout.cache_dir honoured), or None."""
    host = ns_host(settings_path)
    if host is None:
        return None
    try:
        with open(settings_path, encoding='utf-8') as fh:
            base = json.load(fh)['nightscout'].get('cache_dir')
    except (OSError, KeyError, ValueError, TypeError, AttributeError):
        base = None
    base = base or os.path.join(SOFTWARE_DIR, 'ns_cache')
    return os.path.join(base, host)


def day_is_cached(day, cache_dir=None):
    """True when entries/<day>.json and devicestatus/<day>.json exist (treatments may be empty)."""
    cache_dir = cache_dir or ns_cache_dir()
    if not cache_dir:
        return False
    return all(os.path.isfile(os.path.join(cache_dir, coll, day + '.json'))
               for coll in ('entries', 'devicestatus'))


def cached_days(cache_dir=None, days=CACHE_DAYS):
    """The subset of `days` that is cached, in order."""
    return tuple(d for d in days if day_is_cached(d, cache_dir))


def has_module(name):
    return importlib.util.find_spec(name) is not None


# ----------------------------------------------------------------------------- pytest hooks

def pytest_addoption(parser):
    parser.addoption('--run-slow', action='store_true', default=False,
                     help='run tests marked slow (replays, multi-worker runs)')


def pytest_configure(config):
    config.addinivalue_line('markers', 'needs_cache(day=None): skip unless the Nightscout day cache '
                                       '(the whole 2026-08-30..09-07 window, or the given UTC day) exists')
    config.addinivalue_line('markers', 'needs_optuna: skip unless optuna is importable')
    config.addinivalue_line('markers', 'needs_gh: skip unless the gh CLI is on PATH')
    config.addinivalue_line('markers', 'slow: deselected unless --run-slow is given')


def pytest_collection_modifyitems(config, items):
    run_slow = config.getoption('--run-slow')
    cache = ns_cache_dir()
    for item in items:
        marker = item.get_closest_marker('needs_cache')
        if marker is not None:
            days = [a for a in marker.args] or ([marker.kwargs['day']] if marker.kwargs.get('day') else list(CACHE_DAYS))
            missing = [d for d in days if not day_is_cached(d, cache)]
            if missing:
                item.add_marker(pytest.mark.skip(reason='Nightscout cache missing for %s (ns_cache/%s)'
                                                        % (', '.join(missing), os.path.basename(cache or '?'))))
        if item.get_closest_marker('needs_optuna') is not None and not has_module('optuna'):
            item.add_marker(pytest.mark.skip(reason='optuna not installed (optional, see requirements-dev.txt)'))
        if item.get_closest_marker('needs_gh') is not None and shutil.which('gh') is None:
            item.add_marker(pytest.mark.skip(reason='gh CLI not on PATH'))
        if item.get_closest_marker('slow') is not None and not run_slow:
            item.add_marker(pytest.mark.skip(reason='slow test; pass --run-slow'))


